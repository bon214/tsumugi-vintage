/* build/vendor.mjs — materialises the three third-party libraries from
 * node_modules into vendor/, and writes the ES-module shims the app imports.
 *
 * WHY NOT A CDN
 * The editing build pulls React from a CDN script tag and the Supabase SDK
 * through a dynamic `import()` of an esm.sh URL. Both are single points of
 * failure the shop does not control, neither can be pinned with SRI (esm.sh
 * serves a module graph, not one file), and their presence alone forces a CSP
 * that allows a third-party script origin. Copying the exact files that npm
 * resolved removes all three problems and makes the deployed bytes auditable:
 * the version in package.json is the version in vendor/.
 *
 * WHY CLASSIC BUILDS AND SHIMS
 * React publishes reviewed classic browser files. The Supabase package's
 * webpack UMD file contains a global-discovery expression that violates the
 * site's strict CSP, so this script builds a browser IIFE from the package's
 * ESM entry instead. An import map then points bare specifiers at tiny shims.
 *
 *   node build/vendor.mjs
 */

import { readFile, writeFile, mkdir, stat, rm } from "node:fs/promises";
import path from "node:path";
import { createHash } from "node:crypto";
import { build as esbuild } from "esbuild";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "vendor");

/* Exact paths inside each package. If a future version moves them, this fails
   loudly rather than silently shipping nothing. */
const COPIES = [
  { from: "react/umd/react.production.min.js", to: "react.production.min.js", global: "React" },
  { from: "react-dom/umd/react-dom.production.min.js", to: "react-dom.production.min.js", global: "ReactDOM" },
];

const LICENSES = [
  { from: "react/LICENSE", to: "LICENSE.react.txt" },
  { from: "react-dom/LICENSE", to: "LICENSE.react-dom.txt" },
  { from: "@supabase/supabase-js/LICENSE", to: "LICENSE.supabase-js.txt" },
];

/* The shims. Each is the ES module the app's bare specifier resolves to; the
   named exports are exactly the ones this project uses, listed explicitly so a
   missing one is a build error instead of an undefined at runtime. */
const SHIMS = {
  "react.js": `/* GENERATED by build/vendor.mjs — "react" for the no-bundler build.
   The UMD build is loaded as a classic script by the shell, before any module
   runs, so window.React is already present here. */
const React = globalThis.React;
if (!React) throw new Error("vendor/react.js: window.React is missing — the shell must load vendor/react.production.min.js first");
export const {
  createElement, Fragment, Component, PureComponent, cloneElement, isValidElement,
  createContext, createRef, forwardRef, memo, lazy, Children, StrictMode,
  useState, useEffect, useLayoutEffect, useMemo, useCallback, useRef,
  useContext, useReducer, useId, useSyncExternalStore, useTransition,
} = React;
export default React;
`,
  "react-dom-client.js": `/* GENERATED by build/vendor.mjs — "react-dom/client" for the no-bundler build. */
const ReactDOM = globalThis.ReactDOM;
if (!ReactDOM) throw new Error("vendor/react-dom-client.js: window.ReactDOM is missing — the shell must load vendor/react-dom.production.min.js first");
if (!ReactDOM.createRoot) throw new Error("vendor/react-dom-client.js: this ReactDOM build has no createRoot (React 18+ required)");
export const { createRoot, hydrateRoot, flushSync } = ReactDOM;
export default ReactDOM;
`,
  "supabase-js.js": `/* GENERATED by build/vendor.mjs — "@supabase/supabase-js" for the no-bundler
   build. Loaded only by the shells that can sign a user in. */
const sb = globalThis.supabase;
if (!sb) throw new Error("vendor/supabase-js.js: window.supabase is missing — the shell must load vendor/supabase.umd.js first");
export const { createClient, FunctionsHttpError, AuthError } = sb;
export default sb;
`,
};

async function main() {
  const pkg = JSON.parse(await readFile(path.join(ROOT, "package.json"), "utf8"));
  const nm = path.join(ROOT, "node_modules");
  try { await stat(nm); } catch {
    console.error("vendor: node_modules/ is missing. Run `npm ci` first (BUILD.md §2).");
    process.exit(1);
  }

  await rm(OUT, { recursive: true, force: true });
  await mkdir(OUT, { recursive: true });
  const report = [];

  for (const c of [...COPIES, ...LICENSES]) {
    const src = path.join(nm, c.from);
    let buf;
    try { buf = await readFile(src); } catch {
      console.error(`vendor: ${c.from} not found in node_modules — the package layout `
        + `changed for this version; update build/vendor.mjs.`);
      process.exit(1);
    }
    await writeFile(path.join(OUT, c.to), buf);
    if (c.global) {
      report.push({
        file: c.to,
        bytes: buf.length,
        sha256: createHash("sha256").update(buf).digest("base64"),
        global: c.global,
      });
    }
  }

  /* Bundle the installed Supabase ESM graph into a classic browser file. The
     official webpack UMD build uses runtime global discovery that requires
     string compilation; this equivalent IIFE does not and is checked before
     it is written. */
  const disableOptionalTelemetryImport = {
    name: "disable-optional-telemetry-import",
    setup(build) {
      build.onLoad({ filter: /@supabase[\\/]supabase-js[\\/]dist[\\/]index\.mjs$/ }, async (args) => {
        const source = await readFile(args.path, "utf8");
        const optionalLoader = /let otelModulePromise = null;\s*const OTEL_PKG = "@opentelemetry\/api";\s*function loadOtel\(\) \{[\s\S]*?return otelModulePromise;\s*\}/;
        if (!optionalLoader.test(source)) {
          throw new Error("Supabase optional telemetry loader changed shape; review it before updating the vendor build.");
        }
        /* This application neither installs nor enables browser telemetry.
           Replacing the optional computed import with its documented no-module
           result keeps the shipped module graph fully static. */
        return {
          contents: source.replace(optionalLoader,
            "function loadOtel() { return Promise.resolve(null); }"),
          loader: "js",
        };
      });
    },
  };
  const sbBuild = await esbuild({
    stdin: {
      contents: `export * from "@supabase/supabase-js";`,
      resolveDir: ROOT,
      sourcefile: "supabase-vendor-entry.js",
      loader: "js",
    },
    bundle: true,
    format: "iife",
    globalName: "supabase",
    platform: "browser",
    target: ["es2020"],
    minify: true,
    sourcemap: false,
    legalComments: "none",
    plugins: [disableOptionalTelemetryImport],
    write: false,
    logLevel: "silent",
  });
  /* A few transitive modules preserve a no-op string marker identifying a
     compiled typeof helper. It is not a browser compiler, but removing the
     inert marker keeps the strict release scan unambiguous. */
  const sbText = Buffer.from(sbBuild.outputFiles[0].contents).toString("utf8")
    .replaceAll('"@babel/helpers - typeof";', "");
  const sbBuf = Buffer.from(sbText, "utf8");
  if (sbText.includes("new Function") || /\beval\s*\(/.test(sbText)
      || /\bimport\s*\(/.test(sbText) || sbText.includes("sourceMappingURL")
      || sbText.toLowerCase().includes("babel")) {
    console.error("vendor: generated Supabase browser file violates the release CSP gate.");
    process.exit(1);
  }
  await writeFile(path.join(OUT, "supabase.umd.js"), sbBuf);
  report.push({
    file: "supabase.umd.js",
    bytes: sbBuf.length,
    sha256: createHash("sha256").update(sbBuf).digest("base64"),
    global: "supabase",
  });

  for (const [name, body] of Object.entries(SHIMS)) {
    await writeFile(path.join(OUT, name), body, "utf8");
  }

  /* A manifest, so a reviewer can check the deployed bytes against the
     versions in package.json without unpacking node_modules again. */
  const manifest = {
    versions: {
      react: pkg.dependencies.react,
      "react-dom": pkg.dependencies["react-dom"],
      "@supabase/supabase-js": pkg.dependencies["@supabase/supabase-js"],
    },
    files: report,
    shims: Object.keys(SHIMS),
  };
  await writeFile(path.join(OUT, "manifest.json"), JSON.stringify(manifest, null, 2), "utf8");

  console.log("vendor:");
  for (const r of report) console.log(`  ${r.file.padEnd(34)} ${String(r.bytes).padStart(8)} B  window.${r.global}`);
  for (const s of Object.keys(SHIMS)) console.log(`  vendor/${s} (shim)`);
}

main().catch((e) => { console.error(e); process.exit(1); });
